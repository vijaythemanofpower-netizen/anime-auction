// Finds a freely licensed photo of every player on Wikimedia (the photo library behind Wikipedia)
// and writes src/engine/data/photos.ts: player id -> image URL + photographer + licence, so the
// game can show real faces and credit them as the licences require. Non-free ("fair use") images
// are skipped. Run:   npx vite-node tools/photos.ts
import { writeFileSync } from 'node:fs';

const API = 'https://en.wikipedia.org/w/api.php';
const UA = { 'User-Agent': 'CricketAuctionGame/1.0 (https://github.com/vijaythemanofpower-netizen/anime-auction)' };
const FREE = /^(CC0|CC BY(-SA)? [\d.]+|Public domain|PD|Attribution|GFDL|GODL)/i;

import { PLAYERS } from '../src/engine/data/players';
const players = PLAYERS.map((c) => ({ id: c.id, real: c.realName }));

const get = async (params: Record<string, string>): Promise<any> => {
  const r = await fetch(`${API}?${new URLSearchParams({ format: 'json', formatversion: '2', origin: '*', ...params })}`, { headers: UA });
  if (!r.ok) throw new Error(`${r.status}`);
  return r.json();
};
const strip = (html: string = '') => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const surname = (n: string) => (n.split(' ').pop() ?? '').toLowerCase().replace(/[^a-z]/g, '');

const out: Record<string, unknown> = {};
let found = 0;
for (const p of players) {
  try {
    // The player's article: best search hit for "<name> cricketer" whose title contains the surname.
    const s = await get({ action: 'query', generator: 'search', gsrsearch: `${p.real} cricketer`, gsrlimit: '3', prop: 'pageimages', piprop: 'name' });
    const page = (s.query?.pages ?? []).sort((a: any, b: any) => a.index - b.index).find((x: any) => x.title.toLowerCase().replace(/[^a-z ]/g, '').includes(surname(p.real)));
    if (!page?.pageimage) continue;
    const info = await get({ action: 'query', titles: `File:${page.pageimage}`, prop: 'imageinfo', iiprop: 'url|extmetadata', iiurlwidth: '480' });
    const ii = info.query?.pages?.[0]?.imageinfo?.[0];
    const m = ii?.extmetadata ?? {};
    const license = strip(m.LicenseShortName?.value);
    if (!ii?.thumburl || m.NonFree?.value === 'true' || !FREE.test(license)) { if (ii) console.log(`not free: ${p.real}: ${license || '?'}`); continue; }
    out[p.id] = { src: ii.thumburl, page: ii.descriptionurl, author: strip(m.Artist?.value).slice(0, 80) || 'Unknown', license, article: page.title };
    found++;
  } catch (e) { console.log(`skip ${p.real}: ${(e as Error).message}`); }
  await new Promise((r) => setTimeout(r, 120)); // be polite to the API
}

writeFileSync('src/engine/data/photos.ts', `// Generated by tools/photos.mjs: freely licensed photos from Wikimedia Commons. Do not edit by hand.
// Each photo must be shown with its photographer and licence (see the Photo credits list in the app).
export interface PlayerPhoto { src: string; page: string; author: string; license: string; article: string }
export const PHOTOS: Record<string, PlayerPhoto> = ${JSON.stringify(out, null, 1)};
`);
console.log(`${found}/${players.length} players have a free photo`);
