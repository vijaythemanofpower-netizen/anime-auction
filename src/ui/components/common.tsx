const PHASES: Array<{ id: GamePhase[]; label: string }> = [
  { id: ['setup', 'pool'], label: 'Pool' },
  { id: ['auction'], label: 'Auction' },
  { id: ['reveal'], label: 'Reveal' },
  { id: ['hub'], label: 'Tournament' },
  { id: ['prep'], label: 'Prepare' },
  { id: ['battle', 'results'], label: 'Battle' },
  { id: ['champion'], label: 'Champion' },
];

export function PhaseBar({ phase }: { phase: GamePhase }) {
  const idx = PHASES.findIndex((p) => p.id.includes(phase));
  return (
    <nav className="phasebar" aria-label="Game phases">
      {PHASES.map((p, i) => (
        <div key={p.label} className={`phase${i === idx ? ' now' : i < idx || (idx >= 3 && i === 3) ? ' done' : ''}`} aria-current={i === idx ? 'step' : undefined}>{p.label}</div>
      ))}
    </nav>
  );
}

export function Modal({ title, onClose, children, wide }: { title: ReactNode; onClose: () => void; children: ReactNode; wide?: boolean }) {
  useEffect(() => {
    const k = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', k);
    return () => window.removeEventListener('keydown', k);
  }, [onClose]);
  return (
    <div className="overlay" onClick={onClose}>
      <div className="modal" role="dialog" aria-modal="true" onClick={(e) => e.stopPropagation()} style={wide ? { width: 'min(1100px, 100%)' } : undefined}>
        <div className="modal-head">
          <h2 style={{ fontSize: 24 }}>{title}</h2>
          <button className="btn sm ghost" onClick={onClose} aria-label="Close">✕</button>
        </div>
        {children}
      </div>
    </div>
  );
}

export function Seg<T extends string | number>({ value, options, onChange, label }: { value: T; options: Array<{ v: T; label: string; title?: string }>; onChange: (v: T) => void; label?: string }) {
  return (
    <div className="seg" role="group" aria-label={label}>
      {options.map((o) => <button key={String(o.v)} type="button" aria-pressed={o.v === value} title={o.title} onClick={() => onChange(o.v)}>{o.label}</button>)}
    </div>
  );
}

/** Privacy gate: when enabled, the device must be handed to the named player before private info shows. */
export function PrivacyGate({ player, enabled, viewer, children, reason }: { player: Player; enabled: boolean; viewer: string | null; children: ReactNode; reason?: string }) {
  useEffect(() => {
    if (!enabled && viewer !== player.id) store.setViewer(player.id);
  }, [enabled, viewer, player.id]);
  if (!enabled || viewer === player.id) return <>{children}</>;
  return (
    <div className="panel handoff reveal-anim">
      <div className="big-emblem" style={{ background: player.color }}>{player.emblem}</div>
      <div className="eyebrow">Pass the device</div>
      <h2>{player.name}, it&apos;s your turn</h2>
      <p className="muted">{reason ?? 'Private information ahead. Everyone else, look away!'}</p>
      <button className="btn primary lg" onClick={() => store.setViewer(player.id)} autoFocus>I&apos;m {player.name} — show me</button>
    </div>
  );
}
