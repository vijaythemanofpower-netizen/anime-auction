export function Coins({ n }: { n: number }) {
  return <span className="coins">{n.toLocaleString()}</span>;
}

export function Emblem({ p, size = 26 }: { p: Pick<Player, 'color' | 'emblem'>; size?: number }) {
  return <span className="emblem" style={{ background: p.color, width: size, height: size, fontSize: size * 0.5 }} aria-hidden="true">{p.emblem}</span>;
}

export function PlayerChip({ p, suffix }: { p: Player; suffix?: ReactNode }) {
  return (
    <span className="player-chip"><Emblem p={p} />{p.name}{p.kind === 'npc' && <span className="tag gen">NPC</span>}{suffix}</span>
  );
}

export function TagChip({ t }: { t: string }) {
  const color = tagColor(t as never);
  return <span className="tag" style={{ color, borderColor: color + '66' }}>{t}</span>;
}

export function SourceBadge({ c }: { c: PublicCharacter }) {
  if (c.source === 'legend') return <span className="tag src-legend" title="Real anime character; artwork from AniList">ANIME</span>;
  if (c.source === 'mal') return <span className="tag src-anilist" title="Name, image and bio from MyAnimeList (via Jikan); game data generated">MAL</span>;
  return c.source === 'original'
    ? <span className="tag src-original" title="Original character created for this game">ORIGINAL</span>
    : <span className="tag src-anilist" title="Name, image, series and bio from AniList; game data generated">ANILIST</span>;
}

export function CharacterCard({ c, onClick, selected, corner, footer }: { c: PublicCharacter; onClick?: () => void; selected?: boolean; corner?: ReactNode; footer?: ReactNode }) {
  return (
    <div className={`char-card${selected ? ' selected' : ''}`} onClick={onClick} role={onClick ? 'button' : undefined} tabIndex={onClick ? 0 : undefined}
      onKeyDown={(e) => { if (onClick && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); onClick(); } }} aria-label={`${c.name}, ${c.archetype} from ${c.series}`}>
      <div className="art">
        <CharArt c={c} />
        <div className="badges"><SourceBadge c={c} /></div>
        {corner && <div className="corner">{corner}</div>}
        <div className="info">
          <div className="name">{c.name}</div>
          <div className="sub">{c.archetype} · {c.series}</div>
          <div className="row" style={{ gap: 4, marginTop: 6 }}>{c.tags.map((t) => <TagChip key={t} t={t} />)}</div>
        </div>
      </div>
      {footer && <div style={{ padding: 10 }}>{footer}</div>}
    </div>
  );
}

export function PublicProfile({ c }: { c: PublicCharacter }) {
  const gen = (field: string) => c.source !== 'original' && !c.verifiedFields.includes(field) ? <span className="tag gen" title="Generated by the game">game-generated</span> : null;
  return (
    <div className="col" style={{ gap: 10 }}>
      <p className="muted">{c.bio} {c.source === 'anilist' && <span className="tag src-anilist">from AniList</span>}</p>
      {c.aliases.length > 0 && <div className="faint">Also known as: {c.aliases.join(', ')}</div>}
      <div className="grid grid-2" style={{ gap: 8 }}>
        <Info label="Archetype" value={c.archetype} extra={gen('archetype')} hint={ARCHETYPES[c.archetype].description} />
        <Info label="Temperament" value={TEMPERAMENTS[c.temperament].label} extra={gen('temperament')} hint={TEMPERAMENTS[c.temperament].description} />
        <Info label="Specialty" value={c.specialty} extra={gen('specialty')} />
        <Info label="Fighting style" value={c.fightingStyle} extra={gen('fightingStyle')} />
        <Info label="Weapon" value={c.weapon} extra={gen('weapon')} />
        <Info label="Reach" value={c.reach === 'melee' ? 'Melee' : 'Ranged'} />
      </div>
      <div>
        <div className="label" style={{ marginBottom: 6 }}>Known abilities {gen('abilities')}</div>
        <div className="col" style={{ gap: 6 }}>
          {c.knownAbilities.map((id) => <AbilityLine key={id} id={id} />)}
        </div>
      </div>
      <div className="row" style={{ gap: 4 }}>{c.tags.map((t) => <TagChip key={t} t={t} />)}</div>
    </div>
  );
}

function Info({ label, value, extra, hint }: { label: string; value: string; extra?: ReactNode; hint?: string }) {
  return (
    <div style={{ padding: '8px 10px', borderRadius: 10, background: 'rgba(255,255,255,0.03)', border: '1px solid var(--line)' }}>
      <div className="label">{label}</div>
      <div style={{ fontWeight: 600 }}>{value} {extra}</div>
      {hint && <div className="faint">{hint}</div>}
    </div>
  );
}

const TRIGGER_TEXT: Record<string, string> = {
  hp_below_50: 'hurt', hp_below_30: 'badly hurt', ally_low: 'an ally is in trouble', enemy_low: 'an enemy is in trouble', momentum_positive: 'the momentum is theirs',
};

export function AbilityLine({ id, hidden }: { id: string; hidden?: boolean }) {
  const a = getAbility(id);
  return (
    <div style={{ padding: '8px 10px', borderRadius: 10, background: 'rgba(255,255,255,0.03)', borderLeft: `3px solid ${a.fx.color}` }}>
      <div className="row" style={{ gap: 6, justifyContent: 'space-between' }}>
        <strong>{a.name}</strong>
        <span className="faint">{a.kind} · cost {a.cost} · cd {a.cooldown}{a.element ? ` · ${a.element}` : ''}{hidden ? ' · HIDDEN' : ''}</span>
      </div>
      <div className="faint">{a.description}{a.trigger !== 'always' ? ` (Only when ${TRIGGER_TEXT[a.trigger]}.)` : ''}</div>
      {a.look && <div style={{ fontSize: 13, fontStyle: 'italic', color: '#e2e8f0', marginTop: 2 }}>“{a.look}”</div>}
    </div>
  );
}

export function StatBars({ stats, base }: { stats: Stats; base?: Stats }) {
  return (
    <div className="col" style={{ gap: 8 }}>
      {STAT_KEYS.map((k) => {
        const b = base?.[k] ?? stats[k];
        const bonus = stats[k] - b;
        return (
          <div key={k} className="stat-row">
            <span className="muted">{STAT_LABELS[k]}</span>
            <div className="stat-bar" aria-label={`${STAT_LABELS[k]} ${stats[k]}`}>
              <span style={{ width: `${Math.min(100, b)}%` }} />
              {bonus > 0 && <span className="mod" style={{ left: `${Math.min(100, b)}%`, width: `${Math.min(100 - b, bonus)}%` }} />}
            </div>
            <span className="stat-val">{stats[k]}{bonus > 0 && <span style={{ color: 'var(--gold)', fontSize: 11 }}> +{bonus}</span>}</span>
          </div>
        );
      })}
    </div>
  );
}

export function PowerRing({ stats }: { stats: Stats }) {
  const p = truePower(stats);
  const r = 40, c = 2 * Math.PI * r;
  return (
    <svg className="power-ring" viewBox="0 0 100 100" role="img" aria-label={`True Power ${p}`}>
      <circle cx="50" cy="50" r={r} fill="none" stroke="rgba(255,255,255,0.08)" strokeWidth="8" />
      <circle cx="50" cy="50" r={r} fill="none" stroke="url(#pr)" strokeWidth="8" strokeLinecap="round" strokeDasharray={`${(p / 100) * c} ${c}`} transform="rotate(-90 50 50)" />
      <defs><linearGradient id="pr"><stop offset="0" stopColor="#8b5cf6" /><stop offset="1" stopColor="#22d3ee" /></linearGradient></defs>
      <text x="50" y="50" textAnchor="middle" dominantBaseline="central" fill="#fff" fontFamily="Chakra Petch, sans-serif" fontWeight="700" fontSize="26">{p}</text>
      <text x="50" y="72" textAnchor="middle" fill="#a9a7cf" fontSize="9" letterSpacing="1">POWER</text>
    </svg>
  );
}

