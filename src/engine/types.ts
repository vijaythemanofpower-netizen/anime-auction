// ---------------------------------------------------------------- Game

export type GamePhase =
  | 'setup' | 'pool' | 'auction' | 'reveal' | 'hub' | 'prep' | 'battle' | 'results' | 'champion';

export interface GameConfig {
  name: string;
  rosterSize: 3 | 4;
  auction: AuctionConfig;
  tournament: TournamentConfig;
  privacyScreens: boolean;
}

export interface GameState {
  schemaVersion: number;
  id: string;
  createdAt: number;
  updatedAt: number;
  phase: GamePhase;
  config: GameConfig;
  players: Player[];
  pool: string[];
  /** Public data for every character referenced by this game (pool and rosters). */
  characters: Record<string, PublicCharacter>;
  auction: AuctionState | null;
  conditions: Record<string, Condition>;
  prices: Record<string, number>;
  owners: Record<string, string>;
  /** Opponent intel discovered through legitimate scouting: playerId -> charIds. */
  intel: Record<string, string[]>;
  revealSeen: string[];
  tournament: TournamentState | null;
  currentMatchId: string | null;
  prep: Record<string, PrepChoice>;
  battleIds: string[];
  /** Who each player sends into the next raid (their own fighters); missing means "pick my best". */
  raidPicks?: Record<string, string[]>;
  /** Raid Boss attempts, newest last (older saves lack it). */
  raids?: RaidResult[];
  lastBattleId: string | null;
  rivalries: Record<string, Rivalry>;
  secret: number;
  rngState: number;
  archived: boolean;
}

export interface HallEntry {
  id: string;
  gameId: string;
  gameName: string;
  at: number;
  category: 'champion' | 'finalist' | 'upset' | 'comeback' | 'mvp' | 'expensive' | 'value' | 'rivalry' | 'streak' | 'battle';
  title: string;
  detail: string;
  value: number;
}

export interface RaidContribution { charId: string; name: string; playerId: string; dealt: number; tanked: number; healed: number; finalBlow: boolean; score: number; role: string }
export interface RaidResult { id: string; battleId: string; bossId: string; bossName: string; won: boolean; mvp: string | null; contributions: RaidContribution[]; at: number }
